"""Write the CommonMark specification's examples into a MoonBit test corpus.

The `md` frontend is a template frontend: a template written in Markdown is
rendered to Markdown text and then read as Markdown. This corpus checks that
the first half is transparent -- that a document with no template tag in it
comes out of the frontend as the same HTML it would come out of the Markdown
reader itself -- and that the Markdown reader agrees with the specification.

    python scripts/vectors/gen_commonmark.py [spec.json]

The examples are CommonMark 0.31.2, the version moonmd reads. The JSON is
downloaded once and kept beside this script; CI never fetches anything, it
runs the corpus that is committed.

The file is formatted with `moon fmt` at the end, so what this writes is
exactly what the repository holds and `git diff` stays empty after a run.
"""

import json
import pathlib
import subprocess
import sys
import urllib.request

VERSION = "0.31.2"
URL = f"https://spec.commonmark.org/{VERSION}/spec.json"
HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
OUT = ROOT / "src" / "commonmark_suite_test.mbt"
CACHE = HERE / f"commonmark-{VERSION}.json"
PART = 40


def load() -> list:
    given = sys.argv[1] if len(sys.argv) > 1 else None
    for path in [pathlib.Path(given)] if given else [CACHE]:
        if path.is_file():
            return json.loads(path.read_text(encoding="utf-8"))
    text = urllib.request.urlopen(URL).read().decode("utf-8")
    CACHE.write_text(text, encoding="utf-8", newline="\n")
    return json.loads(text)


def literal(text: str) -> str:
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def main() -> int:
    cases = load()
    parts = [cases[i : i + PART] for i in range(0, len(cases), PART)]
    out = [
        f"// Generated by scripts/vectors/gen_commonmark.py from CommonMark {VERSION}.",
        "// Do not edit: change the script and regenerate.",
        "",
        "///|",
        "/// The specification's examples, in order: the number it gives, the",
        "/// section it sits in, the document, and the HTML the document stands",
        "/// for.",
        "fn commonmark_cases() -> Array[(Int32, String, String, String)] {",
        "  let all = []",
    ]
    for i in range(len(parts)):
        out.append(f"  all.append(commonmark_part_{i:02d}()[:])")
    out += ["  all", "}", ""]
    for i, part in enumerate(parts):
        out += ["///|", f"fn commonmark_part_{i:02d}() -> Array[(Int32, String, String, String)] {{",
                "  ["]
        for case in part:
            out.append(
                "    (\n"
                f"      {case['example']}, {literal(case['section'])}, "
                f"{literal(case['markdown'])}, {literal(case['html'])},\n"
                "    ),"
            )
        out += ["  ]", "}", ""]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    subprocess.run(["moon", "fmt", str(OUT)], cwd=ROOT, capture_output=True)
    print(f"{OUT.relative_to(ROOT).as_posix()}: {len(cases)} examples")
    return 0


if __name__ == "__main__":
    sys.exit(main())
