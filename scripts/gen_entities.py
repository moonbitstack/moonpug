#!/usr/bin/env python3
"""Write src/defaults/entities.mbt: the HTML5 named character references,
the code points a numeric reference may not name, and the replacements for
the ones in the C1 range, as Python's html module holds them."""

import html.entities
import html as h
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "defaults" / "entities.mbt"


def escape(s):
    out = []
    for ch in s:
        cp = ord(ch)
        if ch in '\\"':
            out.append("\\" + ch)
        elif 0x20 <= cp < 0x7F:
            out.append(ch)
        else:
            out.append("\\u{%X}" % cp)
    return "".join(out)


def main():
    pairs = sorted(html.entities.html5.items())
    blob = "".join(f"{name}\t{value}\n" for name, value in pairs)
    invalid = sorted(getattr(h, "_invalid_charrefs").items())
    codepoints = sorted(getattr(h, "_invalid_codepoints"))
    lines = [
        "// Generated by scripts/gen_entities.py. Do not edit by hand.",
        "",
        "///|",
        "/// Every named character reference, `name<TAB>text<LF>`; a name that may",
        "/// stand without its semicolon appears both with and without it.",
        f'let entity_data : String = "{escape(blob)}"',
        "",
        "///|",
        "/// Numeric references that name something other than themselves.",
        "let charref_replacements : Array[(Int, String)] = [",
    ]
    lines += [f'  ({cp}, "{escape(text)}"),' for cp, text in invalid]
    lines += ["]", "", "///|", "/// Code points a numeric reference may not produce.", "let charref_dropped : Array[Int] = ["]
    for i in range(0, len(codepoints), 12):
        lines.append("  " + ", ".join(str(c) for c in codepoints[i : i + 12]) + ",")
    lines.append("]")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(pairs)} references")


if __name__ == "__main__":
    main()
